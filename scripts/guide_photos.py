"""Cut the lecture photos out of the BESTEPS lecture posters for the web edition.

Usage:
    python scripts/guide_photos.py [<folder with the posters>]

The folder (default: assets/images/besteps-guide-photos/posters/) holds one poster per chapter, named by the
chapter's slug (opening-lecture, lecture-1 ... lecture-5, closing-lecture) or by the publicity names in ALIASES
(pic_BESTEPS_open, _idea, _org, _vis, _talk, _jmp, _close); any of .jpg/.jpeg/.png/.webp.
Note the posters number two lectures differently from the book: the "Lecture 4" poster (Glitz, the Job
Market Paper) is the book's lecture-5, and the "Lecture 5" poster (Ruiz-Valenzuela, talks) is lecture-4.

Each photo keeps the poster's own framing: the photo area is found by its difference from the poster's blue
background, and everything outside it (the cut corners, the decorative lines, the poster text) becomes
transparent. Writes assets/images/besteps-guide-photos/<slug>.webp and _data/besteps_guide_photos.yml, which
the chapter layout reads. Chapters without a poster simply show no photo.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import yaml
from PIL import Image
from scipy import ndimage

REPO = Path(__file__).resolve().parents[1]
OUT_DIR = REPO / "assets/images/besteps-guide-photos"
URL = "/assets/images/besteps-guide-photos/"
HEADER = "# generated by scripts/guide_photos.py from the lecture posters — do not edit by hand\n"
EXTS = (".jpg", ".jpeg", ".png", ".webp")
MAX_WIDTH = 1400
SMALL_WIDTH = 800
POSTER_BLUE = np.array([0, 90, 140])

# who:      lecturer(s) shown, in left-to-right order
# collage:  the poster combines several cut-out photos; keep that many largest photo areas
# max_y:    lowest row of the photo to keep, as a fraction of the poster height (to leave out a name printed
#           over the bottom of the photo)
POSTERS: dict[str, dict] = {
    "opening-lecture": {"who": ["Antonio Cabrales"], "max_y": 0.752},
    "lecture-1": {"who": ["Libertad González"]},
    "lecture-2": {"who": ["Joan Llull"]},
    "lecture-3": {"who": ["Dirk Foremny", "Guillermo Marín"], "collage": 2},
    "lecture-4": {"who": ["Jenifer Ruiz-Valenzuela"]},
    "lecture-5": {"who": ["Albrecht Glitz"]},
    "closing-lecture": {"who": ["Diego Puga"]},
}

# Poster file names used for the BESTEPS publicity, accepted next to the chapter slugs.
ALIASES = {
    "opening-lecture": ["pic_BESTEPS_open"], "lecture-1": ["pic_BESTEPS_idea"], "lecture-2": ["pic_BESTEPS_org"],
    "lecture-3": ["pic_BESTEPS_vis"], "lecture-4": ["pic_BESTEPS_talk"], "lecture-5": ["pic_BESTEPS_jmp"],
    "closing-lecture": ["pic_BESTEPS_close"],
}


def find_poster(folder: Path, slug: str) -> Path | None:
    for stem in [slug, *ALIASES.get(slug, [])]:
        for e in EXTS:
            if (folder / f"{stem}{e}").exists():
                return folder / f"{stem}{e}"
    return None


def long_runs(nonbg: np.ndarray, min_run: int = 80, gap: int = 6) -> np.ndarray:
    """Per row, keep only stretches of non-background pixels at least min_run wide (drops lines and text)."""
    out = np.zeros_like(nonbg)
    for y in range(nonbg.shape[0]):
        xs = np.flatnonzero(nonbg[y])
        if not len(xs):
            continue
        for seg in np.split(xs, np.flatnonzero(np.diff(xs) > gap) + 1):
            if seg[-1] - seg[0] + 1 >= min_run:
                out[y, seg[0]:seg[-1] + 1] = True
    return out


def framed_photo_mask(nonbg: np.ndarray) -> np.ndarray:
    """The poster's photo frame: a rectangle with 45° cuts at its top-left and bottom-right corners.

    Fitted to the photo area so that photo content close to the poster blue (a banner, a dark coat) is kept."""
    h, w = nonbg.shape
    runs = long_runs(nonbg)
    rows = np.flatnonzero(runs.sum(1) > w * 0.25)
    block = max(np.split(rows, np.flatnonzero(np.diff(rows) > 3) + 1), key=len)   # skip the frame lines
    top, bottom = block[0], block[-1]
    left = np.array([np.flatnonzero(runs[y])[0] for y in block])
    right = np.array([np.flatnonzero(runs[y])[-1] for y in block])
    lm, rm = int(np.median(left)), int(np.median(right))
    cut_tl = [(left[i] - lm) + (y - top) for i, y in enumerate(block) if y - top < 200 and left[i] > lm + 3]
    cut_br = [(rm - right[i]) + (bottom - y) for i, y in enumerate(block) if bottom - y < 220 and right[i] < rm - 3]
    a = int(np.median(cut_tl)) if cut_tl else 0
    b = int(np.median(cut_br)) if cut_br else 0
    yy, xx = np.mgrid[0:h, 0:w]
    return ((yy >= top) & (yy <= bottom) & (xx >= lm) & (xx <= rm)
            & ((xx - lm) + (yy - top) >= a) & ((rm - xx) + (bottom - yy) >= b))


def collage_mask(nonbg: np.ndarray, count: int) -> np.ndarray:
    """The `count` largest cut-out photos of a collage poster."""
    runs = long_runs(nonbg, min_run=40)
    labels, n = ndimage.label(runs)
    sizes = ndimage.sum(runs, labels, range(1, n + 1))
    keep = np.argsort(sizes)[::-1][:count] + 1
    return ndimage.binary_fill_holes(np.isin(labels, keep))


def extract(poster: Path, spec: dict) -> Image.Image:
    """The poster's photo area as an RGBA image, transparent outside the photo frame."""
    with Image.open(poster) as im:
        rgb = np.asarray(im.convert("RGB"))
    h, w, _ = rgb.shape
    nonbg = np.abs(rgb.astype(int) - POSTER_BLUE).sum(2) > 60
    nonbg[:, :25] = nonbg[:, w - 25:] = False                      # the poster's white frame
    mask = collage_mask(nonbg, spec["collage"]) if spec.get("collage") else framed_photo_mask(nonbg)
    if spec.get("max_y"):
        mask[int(spec["max_y"] * h):] = False
    ys, xs = np.flatnonzero(mask.any(1)), np.flatnonzero(mask.any(0))
    rgba = np.dstack([rgb, mask.astype(np.uint8) * 255])[ys[0]:ys[-1] + 1, xs[0]:xs[-1] + 1]
    img = Image.fromarray(rgba)
    if img.width > MAX_WIDTH:
        img = img.resize((MAX_WIDTH, round(img.height * MAX_WIDTH / img.width)), Image.LANCZOS)
    return img


def build(folder: Path, out_dir: Path = OUT_DIR, data_file: Path = REPO / "_data/besteps_guide_photos.yml") -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    data: dict[str, dict] = {}
    written = set()
    for slug, spec in POSTERS.items():
        poster = find_poster(folder, slug)
        if poster is None:
            print(f"no poster for {slug}")
            continue
        img = extract(poster, spec)
        name = f"{slug}.webp"
        img.save(out_dir / name, "WEBP", quality=82, method=6)
        written.add(name)
        who = " and ".join(spec["who"])
        photo = {"src": URL + name, "width": img.width, "height": img.height, "alt": f"{who} lecturing at BESTEPS"}
        if img.width > SMALL_WIDTH:                         # phone-sized copy, offered through srcset
            small_name = f"{slug}-{SMALL_WIDTH}.webp"
            img.resize((SMALL_WIDTH, round(img.height * SMALL_WIDTH / img.width)), Image.LANCZOS).save(
                out_dir / small_name, "WEBP", quality=82, method=6)
            written.add(small_name)
            photo["srcset"] = f"{URL}{small_name} {SMALL_WIDTH}w, {URL}{name} {img.width}w"
        data[slug] = {"photos": [photo], "caption": f"{who} at the BESTEPS lecture."}
        print(f"{slug}: {img.width}×{img.height} from {poster.name}")
    for old in out_dir.glob("*"):
        if old.is_file() and old.name not in written:
            old.unlink()
    data_file.write_text(HEADER + yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")
    return data


if __name__ == "__main__":
    build(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DIR / "posters")
