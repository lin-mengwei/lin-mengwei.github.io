"""Cut the lecture photos out of the BESTEPS lecture posters for the web edition.

Usage:
    python scripts/guide_photos.py [<folder with the posters>]

The folder (default: assets/images/besteps-guide-photos/posters/) holds one poster per chapter, named by the
chapter's slug (opening-lecture, lecture-1 ... lecture-5, closing-lecture) or by the publicity names in ALIASES
(pic_BESTEPS_open, _idea, _org, _vis, _talk, _jmp, _close); any of .jpg/.jpeg/.png/.webp.
Note the posters number two lectures differently from the book: the "Lecture 4" poster (Glitz, the Job
Market Paper) is the book's lecture-5, and the "Lecture 5" poster (Ruiz-Valenzuela, talks) is lecture-4.

Writes assets/images/besteps-guide-photos/<slug>[-n].jpg and _data/besteps_guide_photos.yml, which the chapter
layout reads. Chapters without a poster simply show no photo.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml
from PIL import Image

REPO = Path(__file__).resolve().parents[1]
OUT_DIR = REPO / "assets/images/besteps-guide-photos"
URL = "/assets/images/besteps-guide-photos/"
HEADER = "# generated by scripts/guide_photos.py from the lecture posters — do not edit by hand\n"
EXTS = (".jpg", ".jpeg", ".png", ".webp")
MAX_WIDTH = 1400

# Photo areas inside each poster, as fractions (left, top, right, bottom) of the poster's size, measured on the
# posters of 2025 so that each box stays clear of the poster's cut corners and text overlays.
POSTERS: dict[str, dict] = {
    "opening-lecture": {"date": "10 February 2025", "photos": [
        {"box": (0.22, 0.28, 0.80, 0.735), "who": "Antonio Cabrales"}]},
    "lecture-1": {"date": "20 March 2025", "photos": [
        {"box": (0.176, 0.354, 0.87, 0.60), "who": "Libertad González"}]},
    "lecture-2": {"date": "5 May 2025", "photos": [
        {"box": (0.213, 0.289, 0.895, 0.572), "who": "Joan Llull"}]},
    "lecture-3": {"date": "29 September 2025", "photos": [
        {"box": (0.058, 0.318, 0.43, 0.70), "who": "Dirk Foremny"},
        {"box": (0.545, 0.49, 0.86, 0.80), "who": "Guillermo Marín"}]},
    "lecture-4": {"date": "3 December 2025", "photos": [
        {"box": (0.145, 0.362, 0.667, 0.681), "who": "Jenifer Ruiz-Valenzuela"}]},
    "lecture-5": {"date": "17 November 2025", "photos": [
        {"box": (0.185, 0.319, 0.741, 0.696), "who": "Albrecht Glitz"}]},
    "closing-lecture": {"date": "16 December 2025", "photos": [
        {"box": (0.176, 0.319, 0.741, 0.70), "who": "Diego Puga"}]},
}


# Poster file names used for the BESTEPS publicity, accepted next to the chapter slugs.
ALIASES = {
    "opening-lecture": ["pic_BESTEPS_open"], "lecture-1": ["pic_BESTEPS_idea"], "lecture-2": ["pic_BESTEPS_org"],
    "lecture-3": ["pic_BESTEPS_vis"], "lecture-4": ["pic_BESTEPS_talk"], "lecture-5": ["pic_BESTEPS_jmp"],
    "closing-lecture": ["pic_BESTEPS_close"],
}


def find_poster(folder: Path, slug: str) -> Path | None:
    for stem in [slug, *ALIASES.get(slug, [])]:
        for e in EXTS:
            if (folder / f"{stem}{e}").exists():
                return folder / f"{stem}{e}"
    return None


def crop(poster: Path, box: tuple[float, float, float, float]) -> Image.Image:
    with Image.open(poster) as im:
        im = im.convert("RGB")
        w, h = im.size
        l, t, r, b = box
        part = im.crop((round(l * w), round(t * h), round(r * w), round(b * h)))
    if part.width > MAX_WIDTH:
        part = part.resize((MAX_WIDTH, round(part.height * MAX_WIDTH / part.width)), Image.LANCZOS)
    return part


def build(folder: Path, out_dir: Path = OUT_DIR, data_file: Path = REPO / "_data/besteps_guide_photos.yml") -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    data: dict[str, dict] = {}
    for slug, spec in POSTERS.items():
        poster = find_poster(folder, slug)
        if poster is None:
            print(f"no poster for {slug}")
            continue
        items = []
        for i, ph in enumerate(spec["photos"]):
            name = f"{slug}.jpg" if len(spec["photos"]) == 1 else f"{slug}-{i + 1}.jpg"
            img = crop(poster, ph["box"])
            img.save(out_dir / name, "JPEG", quality=84, optimize=True, progressive=True)
            items.append({"src": URL + name, "width": img.width, "height": img.height,
                          "alt": f"{ph['who']} lecturing at BESTEPS"})
        who = " and ".join(p["who"] for p in spec["photos"])
        data[slug] = {"photos": items, "caption": f"{who} at the BESTEPS lecture, {spec['date']}."}
        print(f"{slug}: {len(items)} photo(s) from {poster.name}")
    data_file.write_text(HEADER + yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")
    return data


if __name__ == "__main__":
    build(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DIR / "posters")
