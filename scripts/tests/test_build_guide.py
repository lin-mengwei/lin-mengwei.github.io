import pytest
import yaml
from bs4 import BeautifulSoup

from build_guide import extract_signature, lookup_lecturers, reading_minutes, reading_order, render_page, resolve_refs
from guide_html import ChapterHTML
from guide_validate import check_images, check_links, check_text

PEOPLE = {"lecturers": [
    {"name": "Guillermo Marín", "tex_name": "Guillermo Marin", "short_affiliation": "Barcelona Supercomputing Center"},
    {"name": "Dirk Foremny", "short_affiliation": "UB & IEB"},
]}


def chapter(html: str) -> ChapterHTML:
    return ChapterHTML(html, [], {}, {}, [], [], "")


def test_resolve_refs_cross_chapter():
    chapters = {
        "opening-lecture": chapter('<p>See Section <a href="#sub:part23" data-reference-type="ref" '
                                   'data-reference="sub:part23">0.3</a> and <a href="#sub:intro1">Intro</a>.</p>'),
        "lecture-2": chapter('<h2 id="part-2-coding">Part 2</h2><p>Figure <a href="#fig:x" '
                             'data-reference-type="ref" data-reference="fig:x">7</a></p>'),
    }
    labels = {
        "sub:part23": ("lecture-2", "part-2-coding", "Part 2: Coding Organized Projects", "section"),
        "sub:intro1": ("opening-lecture", "introduction", "Introduction", "section"),
        "fig:x": ("lecture-2", "figure-1", "1", "figure"),
    }
    assert resolve_refs(chapters, labels, {"opening-lecture": "Opening Lecture", "lecture-2": "Lecture 2"}) == []
    a = BeautifulSoup(chapters["opening-lecture"].html, "lxml").find_all("a")
    assert a[0]["href"] == "/besteps/guide/lecture-2/#part-2-coding"
    assert a[0].get_text() == "Lecture 2 › Part 2: Coding Organized Projects"
    assert not a[0].has_attr("data-reference")
    assert a[1]["href"] == "#introduction" and a[1].get_text() == "Intro"
    fig = BeautifulSoup(chapters["lecture-2"].html, "lxml").find("a")
    assert fig["href"] == "#figure-1" and fig.get_text() == "1"


def test_resolve_refs_unknown_label_reported():
    chapters = {"lecture-1": chapter('<a href="#sub:missing" data-reference-type="ref">??</a>')}
    assert resolve_refs(chapters, {}, {"lecture-1": "Lecture 1"}) == ["lecture-1: #sub:missing"]


def test_people_lookup_accents():
    out = lookup_lecturers(PEOPLE, ["Guillermo Marin", "Dirk Foremny"])
    assert out == [{"name": "Guillermo Marín", "affiliation": "Barcelona Supercomputing Center"},
                   {"name": "Dirk Foremny", "affiliation": "UB & IEB"}]


def test_people_lookup_missing_fails():
    with pytest.raises(KeyError):
        lookup_lecturers(PEOPLE, ["Nobody Known"])


def test_page_wraps_content_in_raw():
    page = render_page({"title": "A: {{ b }}", "order": 1}, "<p>{{ not liquid }} {% if x %}</p>")
    assert page.startswith("---\n# generated by scripts/build_guide.py")
    data = yaml.safe_load(page.split("---")[1])
    assert data["title"] == "A: {{ b }}" and "render_with_liquid" not in data
    body = page.split("---\n", 2)[2]
    assert body.startswith("{% raw %}\n<p>{{ not liquid }}") and body.endswith("{% endraw %}\n")
    with pytest.raises(ValueError):
        render_page({}, "<pre>{% endraw %}</pre>")


def test_reading_order_includes_acknowledgements_and_volume_pages():
    from guide_tex import Chapter
    chs = [Chapter(s, l, t, i + 1, v, "") for i, (s, l, t, v) in enumerate([
        ("preface", "Preface", "Preface", None), ("opening-lecture", "Opening Lecture", "Navigating", 1),
        ("lecture-1", "Lecture 1", "Starting", 1), ("lecture-3", "Lecture 3", "Visualizing", 2),
        ("afterword", "Afterword", "Afterword", None)])]
    order = reading_order(chs, {1: "Set Up Your Research Project", 2: "Produce and Communicate Your Research"})
    assert [o["slug"] for o in order] == ["preface", "acknowledgements", "volume-1", "opening-lecture",
                                          "lecture-1", "volume-2", "lecture-3", "afterword"]
    assert order[2] == {"slug": "volume-1", "label": "Volume 1", "title": "Set Up Your Research Project",
                        "url": "/besteps/guide/volume-1/"}
    assert order[1]["url"] == "/besteps/guide/acknowledgements/"


def test_reading_minutes_rounds_to_five_and_skips_notes_and_code():
    words = " ".join(["word"] * 2544)
    assert reading_minutes(f"<p>{words}</p>") == 15                       # 12.7 min
    assert reading_minutes(f"<p>{' '.join(['w'] * 2279)}</p>") == 10       # 11.4 min
    notes = '<section class="guide-notes"><p>' + " ".join(["n"] * 5000) + "</p></section>"
    code = "<pre>" + " ".join(["c"] * 5000) + "</pre>"
    assert reading_minutes(f"<p>{words}</p>{notes}{code}") == 15
    imgs = '<img src="a.png"/>' * 21                                        # 12 s per figure
    assert reading_minutes(f"<p>{' '.join(['w'] * 4585)}</p>{imgs}") == 25
    assert reading_minutes("<p>short</p>") == 5


def test_extract_signature():
    html = ("<p>Keep going!</p>\n<p><strong>Concepció Patxot</strong><br/>\nDirector, PhD in Economics Program<br/>\n"
            "University of Barcelona</p>")
    body, byline = extract_signature(html)
    assert body == "<p>Keep going!</p>"
    assert byline == {"name": "Concepció Patxot",
                      "lines": ["Director, PhD in Economics Program", "University of Barcelona"]}
    assert extract_signature("<p>Plain <strong>bold</strong> text.</p>")[1] is None


def test_validate_detects_residual_latex():
    assert check_text("lecture-1", "<p>Some \\textbf{bold} text</p>")
    assert check_text("lecture-1", "<p>Plain text</p><pre>{ braces } ok</pre>") == []


def test_validate_detects_missing_image(tmp_path):
    (tmp_path / "a.png").write_bytes(b"x")
    assert check_images(["a.png"], tmp_path) == []
    assert check_images(["b.png"], tmp_path) == ["missing image: b.png"]


def test_validate_links():
    pages = {"lecture-1": '<h2 id="a">A</h2><a href="#a">ok</a><a href="/besteps/guide/lecture-2/#b">x</a>',
             "lecture-2": '<h2 id="c">C</h2><a href="#nowhere">bad</a>'}
    assert check_links(pages) == ["lecture-1: broken link /besteps/guide/lecture-2/#b",
                                  "lecture-2: broken link #nowhere"]
