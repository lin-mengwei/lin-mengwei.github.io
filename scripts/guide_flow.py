"""Turn the draw.io export of the BESTEPS flow diagram into the inline SVG used on the guide home page.

Usage:
    python scripts/guide_flow.py [<exported .svg>]

Input (default): besteps/guide/besteps.drawio.svg, exported from draw.io as SVG.
Each lecture's label and arrow, and each volume's label and brace, become links (see LINKS below).
Output: _includes/guide-flow.svg, which the home layout includes inline.

The web copy drops what draw.io adds for its own editor and for old browsers: the embedded diagram
source, the PNG fallback behind every text label, and the automatic dark-mode colours (the guide pages are
always light, so light-dark(a, b) becomes a). It also drops the fixed pixel size so the diagram scales.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "besteps/guide/besteps.drawio.svg"
OUT = REPO / "_includes/guide-flow.svg"
HEADER = "<!-- generated by scripts/guide_flow.py from besteps/guide/besteps.drawio.svg — do not edit by hand -->\n"


def _split_args(s: str, start: int) -> tuple[list[str], int]:
    """Arguments of the call whose '(' is at s[start]; returns (args, index after ')')."""
    depth, args, cur, i = 0, [], [], start
    while i < len(s):
        ch = s[i]
        if ch == "(":
            depth += 1
            if depth > 1:
                cur.append(ch)
        elif ch == ")":
            depth -= 1
            if depth == 0:
                args.append("".join(cur).strip())
                return args, i + 1
            cur.append(ch)
        elif ch == "," and depth == 1:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
        i += 1
    raise ValueError("unbalanced light-dark()")


def light_only(s: str) -> str:
    """Replace every light-dark(a, b) with a."""
    out, pos = [], 0
    while (i := s.find("light-dark(", pos)) != -1:
        args, end = _split_args(s, i + len("light-dark"))
        out.append(s[pos:i])
        out.append(light_only(args[0]))
        pos = end
    out.append(s[pos:])
    return "".join(out)


GUIDE_URL = "/besteps/guide/"

# Clickable parts of the diagram, by the draw.io cell number (the part after the last "-" of data-cell-id;
# cell ids survive editing in draw.io). Each target lists its label cell, the text the label must contain
# (checked, so a re-drawn diagram cannot silently link the wrong lecture), and its arrow or brace cells.
LINKS = {
    "opening-lecture": {"label": "11", "text": "Opening Lecture", "parts": ["5"], "name": "Opening Lecture"},
    "lecture-1": {"label": "8", "text": "Lecture 1", "parts": ["2"], "name": "Lecture 1"},
    "lecture-2": {"label": "12", "text": "Lecture 2", "parts": ["6"], "name": "Lecture 2"},
    "lecture-3": {"label": "13", "text": "Lecture 3", "parts": ["3"], "name": "Lecture 3"},
    "lecture-4": {"label": "14", "text": "Lecture 4", "parts": ["7"], "name": "Lecture 4"},
    "lecture-5": {"label": "16", "text": "Lecture 5", "parts": ["15"], "name": "Lecture 5"},
    "closing-lecture": {"label": "26", "text": "Closing", "parts": ["4"], "name": "Closing Lecture"},
    "volume-1": {"label": "17", "text": "Volume 1", "parts": ["23"], "name": "Volume 1 introduction"},
    "volume-2": {"label": "18", "text": "Volume 2", "parts": ["24"], "name": "Volume 2 introduction"},
}


def _group_span(svg: str, cell: str) -> tuple[int, int]:
    """Start and end of the <g data-cell-id="...-cell"> element."""
    m = re.search(r'<g data-cell-id="[^"]*-' + re.escape(cell) + r'">', svg)
    if not m:
        raise ValueError(f"diagram cell {cell} not found; update LINKS in scripts/guide_flow.py")
    depth, i = 0, m.start()
    for t in re.finditer(r"<g[\s>]|</g>", svg[m.start():]):
        depth += -1 if t.group(0) == "</g>" else 1
        if depth == 0:
            return m.start(), m.start() + t.end()
    raise ValueError(f"unbalanced <g> for cell {cell}")


def add_links(svg: str, links: dict = LINKS) -> str:
    """Wrap each lecture's label and arrow (and each volume's label and brace) in a link to its page."""
    wraps = []
    for slug, spec in links.items():
        start, end = _group_span(svg, spec["label"])
        text = re.sub(r"<[^>]+>|&nbsp;", " ", svg[start:end])
        if spec["text"] not in re.sub(r"\s+", " ", text):
            raise ValueError(f"diagram cell {spec['label']} does not read {spec['text']!r}: {text.strip()[:60]!r}")
        href = f"{GUIDE_URL}{slug}/"
        wraps.append((start, end, f'<a href="{href}" class="guide-flow-link" data-flow="{slug}" '
                                  f'aria-label="{spec["name"]}">'))
        for part in spec["parts"]:
            ps, pe = _group_span(svg, part)
            wraps.append((ps, pe, f'<a href="{href}" class="guide-flow-link" data-flow="{slug}" '
                                  f'tabindex="-1" aria-hidden="true">'))
    for start, end, open_tag in sorted(wraps, reverse=True):
        svg = svg[:start] + open_tag + svg[start:end] + "</a>" + svg[end:]
    return svg


def clean(svg: str, links: dict = LINKS) -> str:
    svg = svg[svg.index("<svg"):]                                              # XML declaration, doctype, comment
    svg = re.sub(r"<switch>(<foreignObject.*?</foreignObject>)<image[^>]*/></switch>", r"\1", svg, flags=re.S)
    svg = re.sub(r'\s(?:requiredFeatures)="[^"]*"', "", svg)
    svg = re.sub(r"<style[^>]*>@supports.*?</style>", "", svg, flags=re.S)
    svg = re.sub(r'<rect fill="#ffffff" width="100%" height="100%"[^>]*/>', "", svg, count=1)
    svg = light_only(svg)
    svg = re.sub(r"<a\s[^>]*>|</a>", "", svg)                                 # links are added by the page

    m = re.match(r"<svg[^>]*>", svg)
    attrs = m.group(0)
    view_box = re.search(r'viewBox="([^"]*)"', attrs).group(1)
    root = (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" version="1.1" '
            f'viewBox="{view_box}" class="guide-flow-svg" role="group" '
            f'aria-label="The BESTEPS lectures along the life cycle of a research project, '
            f'grouped into Volume 1 and Volume 2 of The BESTEPS Guide">')
    svg = add_links(root + svg[m.end():], links)
    if "{{" in svg or "{%" in svg:
        raise ValueError("diagram text contains Liquid syntax")
    if "<image" in svg or "base64," in svg:
        raise ValueError("raster fallback left in the SVG")
    return HEADER + svg.strip() + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    src = Path(argv[0]) if argv else SRC
    text = clean(src.read_text(encoding="utf-8"))
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(REPO)}: {len(text) // 1024} KB (from {src.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
