"""Generate the web edition of The BESTEPS Guide from Print.tex.

Usage:
    python scripts/build_guide.py <Print.tex or its folder> [--cover <cover.pdf>]

Writes (and overwrites) only generated files:
    _guide/*.html                         one page per chapter (Jekyll collection)
    _data/besteps_guide.yml               home-page fragments
    assets/data/besteps-guide-search.json search index
    assets/images/besteps-guide/*         figures, logo, cover
Exits with status 1 when any validation fails.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

import yaml
from bs4 import BeautifulSoup
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))

import guide_tex  # noqa: E402
from guide_html import ChapterHTML, postprocess, to_html  # noqa: E402
from guide_validate import check_counts, check_images, check_links, check_text, source_counts  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
GUIDE_URL = "/besteps/guide/"
GUIDE_IMG = "/assets/images/besteps-guide/"
HEADER = "# generated by scripts/build_guide.py from Print.tex — do not edit by hand"
EXTRA_IMAGES: list[str] = []
SITE_PDF = "assets/files/BESTEPS_Guide_Content.pdf"


def _fold(s: str) -> str:
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower().strip()


def lookup_lecturers(people: dict, names: list[str]) -> list[dict]:
    out = []
    for n in names:
        hit = next((p for p in people["lecturers"]
                    if n in (p["name"], p.get("tex_name")) or _fold(n) == _fold(p["name"])), None)
        if hit is None:
            raise KeyError(f"lecturer not in _data/besteps_guide_people.yml: {n}")
        out.append({"name": hit["name"], "affiliation": hit["short_affiliation"]})
    return out


def front_matter(meta: dict) -> str:
    body = yaml.safe_dump(meta, allow_unicode=True, sort_keys=False, width=1000)
    return f"---\n{HEADER}\n{body}---\n"


def render_page(meta: dict, html: str) -> str:
    """Front matter plus the chapter wrapped in a raw block so Liquid never touches the text.
    (GitHub Pages builds with Jekyll 3, which ignores `render_with_liquid: false`.)"""
    if "endraw" in html:
        raise ValueError("chapter text contains 'endraw', which would end the raw block")
    return front_matter(meta) + "{% raw %}\n" + html + "\n{% endraw %}\n"


def resolve_refs(chapters: dict[str, ChapterHTML], labels: dict[str, tuple[str, str, str, str]],
                 short_labels: dict[str, str]) -> list[str]:
    """Rewrite '#label' links to their final anchors; return the labels that could not be resolved."""
    unresolved = []
    for slug, ch in chapters.items():
        s = BeautifulSoup(f"<div id='r'>{ch.html}</div>", "lxml")
        root = s.find("div", id="r")
        ids = {el["id"] for el in root.find_all(id=True)}
        for a in root.find_all("a", href=True):
            href = a["href"]
            if not href.startswith("#") or href[1:] in ids:
                continue
            is_ref = a.get("data-reference-type") == "ref"
            for attr in ("data-reference-type", "data-reference"):
                a.attrs.pop(attr, None)
            target = labels.get(href[1:])
            if target is None:
                unresolved.append(f"{slug}: {href}")
                continue
            t_slug, anchor, text, kind = target
            same = t_slug == slug
            a["href"] = f"#{anchor}" if same else f"{GUIDE_URL}{t_slug}/" + (f"#{anchor}" if anchor else "")
            if is_ref:
                a.string = text if (same or kind == "figure") else f"{short_labels[t_slug]} › {text}"
        ch.html = "".join(str(c) for c in root.contents)
    return unresolved


def extract_signature(html: str) -> tuple[str, dict | None]:
    """Move a closing signature paragraph (<p><strong>Name</strong><br/>line<br/>line</p>) out of the body.
    Returns the body without it and {"name", "lines"} for a byline under the title."""
    s = BeautifulSoup(f"<div id='r'>{html}</div>", "lxml")
    root = s.find("div", id="r")
    paras = root.find_all("p", recursive=False)
    if not paras:
        return html, None
    p = paras[-1]
    first = next((c for c in p.contents if not (isinstance(c, str) and not c.strip())), None)
    if getattr(first, "name", None) != "strong" or not p.find("br"):
        return html, None
    parts = [re.sub(r"\s+", " ", t).strip() for t in p.get_text("\n").split("\n")]
    parts = [t for t in parts if t]
    p.decompose()
    return "".join(str(c) for c in root.contents).strip(), {"name": parts[0], "lines": parts[1:]}


def reading_order(chapters, volume_titles: dict[int, str]) -> list[dict]:
    """Every guide page in reading order, as the sidebar lists them: the acknowledgements follow the preface,
    and each volume's introduction page comes before its first lecture. Drives the previous/next links."""
    def entry(slug, label, title):
        return {"slug": slug, "label": label, "title": title, "url": f"{GUIDE_URL}{slug}/"}

    order, volume = [], None
    for c in chapters:
        if c.volume and c.volume != volume:
            order.append(entry(f"volume-{c.volume}", f"Volume {c.volume}", volume_titles[c.volume]))
        volume = c.volume or volume
        order.append(entry(c.slug, c.label, c.title))
        if c.slug == "preface":
            order.append(entry("acknowledgements", "Acknowledgements", "Acknowledgements"))
    return order


WORDS_PER_MINUTE = 200        # dense academic prose, many readers not native English speakers
SECONDS_PER_FIGURE = 12


def reading_minutes(html: str) -> int:
    """Estimated reading time of a chapter, rounded to the nearest 5 minutes (at least 5).
    Footnotes and code blocks are left out; each image adds a few seconds."""
    s = BeautifulSoup(f"<div>{html}</div>", "lxml")
    for el in s.select(".guide-notes, pre"):
        el.decompose()
    words = len(re.findall(r"\w[\w'’-]*", s.get_text(" ")))
    minutes = words / WORDS_PER_MINUTE + len(s.find_all("img")) * SECONDS_PER_FIGURE / 60
    return max(5, int(5 * round(minutes / 5)))


SIGNED_AT_TOP = {"preface"}   # chapters whose closing signature is shown as a byline under the title


def _fragment_html(tex: str) -> str:
    return postprocess(to_html(guide_tex.preprocess(tex)), "home", {}).html


def _image_sources(src: str, folder: Path) -> dict[str, Path]:
    paths = re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}", src)
    out = {Path(p).name: folder / p for p in paths}
    out.update({n: folder / n for n in EXTRA_IMAGES})
    return out


MAX_WIDTH = 1600
MAX_PNG_BYTES = 400_000


def _publish_image(src: Path, img_dir: Path) -> str:
    """Write a web-sized copy of src into img_dir; return the published file name."""
    import io
    with Image.open(src) as im:
        im.load()
        if im.mode not in ("RGB", "RGBA", "L", "LA", "P"):
            im = im.convert("RGB")
        if im.width > MAX_WIDTH:
            im = im.resize((MAX_WIDTH, round(im.height * MAX_WIDTH / im.width)), Image.LANCZOS)
        buf = io.BytesIO()
        is_jpeg = src.suffix.lower() in (".jpg", ".jpeg")
        if is_jpeg:
            im.convert("RGB").save(buf, "JPEG", quality=85)
        else:
            im.save(buf, "PNG", optimize=True)
        name, data = src.name, buf.getvalue()
        if len(data) > MAX_PNG_BYTES and not is_jpeg:
            buf = io.BytesIO()
            im.save(buf, "WEBP", quality=85, method=6)
            name, data = src.stem + ".webp", buf.getvalue()
    dest = img_dir / name
    if not dest.exists() or dest.read_bytes() != data:
        dest.write_bytes(data)
    return name


def _add_image_sizes(html: str, img_dir: Path, web_names: dict[str, str]) -> str:
    s = BeautifulSoup(f"<div id='r'>{html}</div>", "lxml")
    for img in s.find_all("img"):
        prefix, name = img["src"].rsplit("/", 1)
        img["src"] = f"{prefix}/{web_names.get(name, name)}"
        path = img_dir / web_names.get(name, name)
        if path.exists():
            with Image.open(path) as im:
                img["width"], img["height"] = str(im.width), str(im.height)
    return "".join(str(c) for c in s.find("div", id="r").contents)


def _render_cover(pdf: Path, img_dir: Path):
    import fitz
    with fitz.open(pdf) as doc:
        page = doc[0]
        for name, height in (("cover.jpg", 1200), ("cover-thumb.jpg", 420)):
            zoom = height / page.rect.height
            pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom))
            Image.frombytes("RGB", (pix.width, pix.height), pix.samples).save(img_dir / name, quality=88)


def _write(path: Path, text: str, written: list[Path]):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")
    written.append(path)


def build(source: Path, repo: Path = REPO, cover: Path | None = None) -> int:
    source = Path(source)
    tex_path = source / "Print.tex" if source.is_dir() else source
    src = tex_path.read_text(encoding="utf-8")
    chapters, frags = guide_tex.split_book(src)
    people = yaml.safe_load((repo / "_data/besteps_guide_people.yml").read_text(encoding="utf-8"))
    img_dir = repo / "assets/images/besteps-guide"
    img_dir.mkdir(parents=True, exist_ok=True)
    failures: list[str] = []
    written: list[Path] = []

    results: dict[str, ChapterHTML] = {}
    labels: dict[str, tuple[str, str, str, str]] = {}
    rows = []
    for ch in chapters:
        r = postprocess(to_html(guide_tex.preprocess(ch.tex)), ch.slug, guide_tex.image_widths(ch.tex))
        results[ch.slug] = r
        for lab, (anchor, text, kind) in r.labels.items():
            labels[lab] = (ch.slug, anchor, text, kind)
        src_counts = source_counts(ch.tex)
        failures += check_counts(ch.slug, src_counts, r.counts)
        rows.append((ch.slug, src_counts, r.counts))
    failures += [f"unresolved reference {u}" for u in
                 resolve_refs(results, labels, {c.slug: c.label for c in chapters})]

    sources = _image_sources(src, tex_path.parent)
    web_names: dict[str, str] = {}
    for name in sorted({n for r in results.values() for n in r.images} | set(EXTRA_IMAGES)):
        if name not in sources or not sources[name].exists():
            failures.append(f"image not found in source folder: {name}")
            continue
        web_names[name] = _publish_image(sources[name], img_dir)
    if cover:
        _render_cover(Path(cover), img_dir)
    keep = set(web_names.values()) | {"cover.jpg", "cover-thumb.jpg"}
    if not any(f.startswith("image not found") for f in failures):  # never prune from a half-synced source
        for f in img_dir.iterdir():
            if f.name not in keep:
                f.unlink()

    used_people = set()
    search = []
    for ch in chapters:
        r = results[ch.slug]
        try:
            lecturers = lookup_lecturers(people, guide_tex.lecturer_names(ch.tex))
        except KeyError as e:
            failures.append(str(e))
            lecturers = []
        used_people |= {p["name"] for p in lecturers}
        if re.search(r"[\\{}~]|``|''", ch.title + ch.label):
            failures.append(f"{ch.slug}: LaTeX left in chapter title {ch.title!r}")
        if not r.description:
            failures.append(f"{ch.slug}: empty description")
        if not r.sections and ch.slug not in ("preface", "afterword"):
            failures.append(f"{ch.slug}: no sections")
        failures += check_text(ch.slug, r.html)
        failures += check_images([web_names.get(n, n) for n in r.images], img_dir)

        meta = {
            "layout": "guide", "body_id": "guide", "nav_active": "public-goods",
            "title": ch.title, "short_title": ch.label, "slug": ch.slug,
            "permalink": f"{GUIDE_URL}{ch.slug}/", "order": ch.order, "volume": ch.volume,
            "lecturers": lecturers, "description": r.description, "sections": r.sections,
        }
        html = _add_image_sizes(r.html, img_dir, web_names)
        if ch.volume:                                   # lectures only, not the preface or afterword
            meta["reading_minutes"] = reading_minutes(html)
        if ch.slug in SIGNED_AT_TOP:
            html, byline = extract_signature(html)
            if byline is None:
                failures.append(f"{ch.slug}: expected a closing signature to move under the title")
            meta["byline"] = byline
        try:
            _write(repo / "_guide" / f"{ch.slug}.html", render_page(meta, html), written)
        except ValueError as e:
            failures.append(f"{ch.slug}: {e}")
        for e in r.search:
            search.append({"chapter": ch.label, "title": ch.title, "section": e["section"],
                           "url": f"{GUIDE_URL}{ch.slug}/" + (f"#{e['anchor']}" if e["anchor"] else ""),
                           "text": e["text"]})
    unused = {p["name"] for p in people["lecturers"]} - used_people
    failures += [f"people table entry matches no chapter: {n}" for n in sorted(unused)]
    failures += check_links({slug: r.html for slug, r in results.items()})

    data = {
        "images": {"cover": GUIDE_IMG + "cover.jpg", "cover_thumb": GUIDE_IMG + "cover-thumb.jpg"},
        "blurb": _fragment_html(frags["blurb"]),
        "acknowledgements": _fragment_html(frags["acknowledgements"]),
        "volumes": [{"number": n, "title": frags[f"volume{n}_title"],
                     "intro": _fragment_html(frags[f"volume{n}_intro"])} for n in (1, 2)],
        "reading_order": reading_order(chapters, {n: frags[f"volume{n}_title"] for n in (1, 2)}),
    }
    for key in ("blurb", "acknowledgements"):
        failures += check_text(f"home {key}", data[key])
    _write(repo / "_data/besteps_guide.yml",
           HEADER + "\n" + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000), written)
    _write(repo / "assets/data/besteps-guide-search.json",
           json.dumps(search, ensure_ascii=False, indent=1) + "\n", written)

    for stale in (repo / "_guide").glob("*.html"):
        if stale not in written and HEADER in stale.read_text(encoding="utf-8"):
            stale.unlink()

    _report(rows, failures, tex_path, repo)
    return 1 if failures else 0


def _report(rows, failures, tex_path: Path, repo: Path):
    keys = list(rows[0][1])
    print(f"{'chapter':<17}" + "".join(f"{k:>10}" for k in keys))
    for slug, s, o in rows:
        print(f"{slug:<17}" + "".join(f"{(str(o.get(k, 0)) if s[k] == o.get(k, 0) else f'{o.get(k, 0)}≠{s[k]}'):>10}"
                                      for k in keys))
    for w in dict.fromkeys(guide_tex.WARNINGS):
        print(f"WARNING: {w}")
    pdf = repo / SITE_PDF
    if pdf.exists() and pdf.stat().st_mtime < tex_path.stat().st_mtime:
        print(f"WARNING: {SITE_PDF} is older than Print.tex; recompile and upload the PDF if the text changed.")
    for f in failures:
        print(f"FAIL: {f}")
    print("OK: all checks passed" if not failures else f"{len(failures)} check(s) failed")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("source", type=Path, help="Print.tex or the folder that contains it")
    p.add_argument("--cover", type=Path, help="cover PDF; page 1 is rendered to cover.jpg")
    a = p.parse_args(argv)
    return build(a.source, REPO, a.cover)


if __name__ == "__main__":
    sys.exit(main())
